# ── 字符间多余空格清理（PDF 排版常见） ──────────────────────────────
# 匹配 CJK 字符（包含扩展 A、扩展 B 等）
_CJK_RE = r"[一-鿿　-〿＀-￯]"


def normalize_kangxi_chars(text: str) -> str:
    """将康熙部首区字符映射回标准 CJK 区"""
    if not text:
        return text
    return "".join(_KANGXI_TO_CJK.get(c, c) for c in text)


def collapse_cjk_spaces(text: str) -> str:
    """压缩 CJK 字符之间的多余空格（仅在异体字归一化后才有意义）

    工作原理：先归一化异体字，然后剩余的 CJK-CJK 之间的空格
    多半是 PDF 排版引入的多余空格，可以安全删除。

    但要小心：CJK 与英文/数字之间的空格是有意义的（分词、视觉效果），
    不应删除。

    例（异体字已先归一化为标准 CJK）：
    - "项 ⽬" → "项目" (CJK-CJK)
    - "Pico 项目" 保留 "Pico 项目" (英文-中文 保留)
    - "100 个" 保留 "100 个" (数字-中文 保留)
    """
    if not text:
        return text
    # 仅压缩「CJK 紧邻 CJK」的多余空格（先归一化异体字后再做这步才有意义）
    text = re.sub(rf"({_CJK_RE})\s+({_CJK_RE})", r"\1\2", text)
    return text


def normalize_pdf_text(text: str) -> str:
    """
    完整的 PDF 文本归一化流水线

    Args:
        text: 原始 PDF 提取的文本

    Returns:
        归一化后的干净文本
    """
    if not text:
        return text

    # Step 1: Unicode 标准化（兼容分解 + 重组）
    text = unicodedata.normalize("NFKC", text)

    # Step 2: 归一化康熙部首
    text = normalize_kangxi_chars(text)

    # Step 3: 清理 CJK 字符间多余空格
    text = collapse_cjk_spaces(text)

    # Step 4: 清理连续空白
    text = re.sub(r"[ \t]+", " ", text)

    # Step 5: 合并多余换行（连续 3+ 个 → 2 个）
    text = re.sub(r"\n{3,}", "\n\n", text)

    # Step 6: 移除 NUL 和其他控制字符
    text = text.replace("\x00", "")

    return text.strip()


def is_cjk_char(ch: str) -> bool:
    """判断是否为 CJK 字符"""
    if not ch:
        return False
    return bool(re.match(_CJK_RE, ch))


